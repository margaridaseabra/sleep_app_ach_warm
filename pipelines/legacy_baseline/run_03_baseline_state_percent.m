%% RUN_03_BASELINE_STATE_PERCENT
%
% Baseline APP vs WT sleep-state analysis.
%
% Analyses:
%   thesis cohort
%   new cohort
%   combined cohort
%
% Time bins:
%   ZT3-6
%   ZT6-9
%
% States:
%   WK
%   NREM
%   REM
%   MA
%
% Separate-cohort statistics:
%   Welch APP vs WT t-test
%
% Combined statistics:
%   Genotype x Cohort two-way model
%
% Figures show individual mice and mean +/- SEM.

clear;
clc;

%% Setup

pipelineDir = fileparts(mfilename('fullpath'));
repoDir = fileparts(pipelineDir);

addpath(fullfile(repoDir, 'config'));

P = paths_config();

inFile = fullfile( ...
    P.sleep_output, ...
    'all', ...
    'sleep_state_3h_bins.csv');

S = readtable(inFile, ...
    'TextType','string', ...
    'VariableNamingRule','preserve');

outDir = fullfile( ...
    P.sleep_output, ...
    'baseline');

if ~isfolder(outDir)
    mkdir(outDir);
end

%% Select baseline primary-analysis data

includePrimary = to_logical(S.include_primary);

BASE = S( ...
    S.condition == "baseline" & ...
    includePrimary & ...
    ismember(S.time_bin, ["ZT3_6","ZT6_9"]) & ...
    ismember(S.state, ["WK","NREM","REM","MA"]), :);

fprintf('\n========================================\n');
fprintf('BASELINE SLEEP ARCHITECTURE\n');
fprintf('========================================\n');

fprintf('Rows included: %d\n\n', height(BASE));

%% Check sample sizes

views = ["thesis","new","all"];
bins = ["ZT3_6","ZT6_9"];
states = ["WK","NREM","REM","MA"];

fprintf('Mouse counts:\n');

for v = 1:numel(views)

    if views(v) == "all"
        D = BASE;
    else
        D = BASE(BASE.cohort == views(v), :);
    end

    oneRow = D( ...
        D.time_bin == "ZT3_6" & ...
        D.state == "REM", :);

    fprintf('%-8s  WT=%d  APP=%d\n', ...
        views(v), ...
        sum(oneRow.genotype == "WT"), ...
        sum(oneRow.genotype == "APP"));
end

%% Welch APP vs WT tests

WELCH = table();

for v = 1:numel(views)

    viewName = views(v);

    if viewName == "all"
        Dview = BASE;
    else
        Dview = BASE(BASE.cohort == viewName, :);
    end

    for b = 1:numel(bins)

        binName = bins(b);

        for s = 1:numel(states)

            stateName = states(s);

            D = Dview( ...
                Dview.time_bin == binName & ...
                Dview.state == stateName, :);

            wt = double(D.percent_time(D.genotype == "WT"));
            app = double(D.percent_time(D.genotype == "APP"));

            wt = wt(~isnan(wt));
            app = app(~isnan(app));

            nWT = numel(wt);
            nAPP = numel(app);

            meanWT = mean(wt);
            meanAPP = mean(app);

            semWT = std(wt) / sqrt(nWT);
            semAPP = std(app) / sqrt(nAPP);

            meanDifference = meanAPP - meanWT;

            pValue = NaN;
            tStat = NaN;
            df = NaN;

            if nWT >= 2 && nAPP >= 2

                [~, pValue, ~, stats] = ...
                    ttest2(app, wt, ...
                    'Vartype','unequal');

                tStat = stats.tstat;
                df = stats.df;
            end

            row = table( ...
                viewName, ...
                binName, ...
                stateName, ...
                nWT, ...
                nAPP, ...
                meanWT, ...
                semWT, ...
                meanAPP, ...
                semAPP, ...
                meanDifference, ...
                tStat, ...
                df, ...
                pValue, ...
                'VariableNames', { ...
                    'cohort_view', ...
                    'time_bin', ...
                    'state', ...
                    'n_WT', ...
                    'n_APP', ...
                    'WT_mean', ...
                    'WT_SEM', ...
                    'APP_mean', ...
                    'APP_SEM', ...
                    'APP_minus_WT', ...
                    't_stat', ...
                    'df', ...
                    'p_welch'});

            WELCH = [WELCH; row];

        end
    end
end

welchFile = fullfile( ...
    outDir, ...
    'baseline_state_percent_welch.csv');

writetable(WELCH, welchFile);

%% Combined cohort model
%
% Type III two-way model:
%
% percent_time ~ Genotype * Cohort
%
% This tests:
%   Genotype
%   Cohort
%   Genotype x Cohort

MODEL = table();

for b = 1:numel(bins)

    for s = 1:numel(states)

        D = BASE( ...
            BASE.time_bin == bins(b) & ...
            BASE.state == states(s), :);

        y = double(D.percent_time);

        genotype = cellstr(D.genotype);
        cohort = cellstr(D.cohort);

        pGenotype = NaN;
        pCohort = NaN;
        pInteraction = NaN;

        try

            p = anovan( ...
                y, ...
                {genotype, cohort}, ...
                'model','interaction', ...
                'sstype',3, ...
                'display','off', ...
                'varnames',{'Genotype','Cohort'});

            if numel(p) >= 3
                pGenotype = p(1);
                pCohort = p(2);
                pInteraction = p(3);
            end

        catch ME

            warning( ...
                'Combined model failed for %s %s: %s', ...
                bins(b), states(s), ME.message);
        end

        row = table( ...
            bins(b), ...
            states(s), ...
            pGenotype, ...
            pCohort, ...
            pInteraction, ...
            'VariableNames', { ...
                'time_bin', ...
                'state', ...
                'p_genotype', ...
                'p_cohort', ...
                'p_genotype_x_cohort'});

        MODEL = [MODEL; row];

    end
end

modelFile = fullfile( ...
    outDir, ...
    'baseline_state_percent_genotype_cohort_model.csv');

writetable(MODEL, modelFile);

%% Plot settings

stateLabels = [ ...
    "Wake", ...
    "NREM", ...
    "REM", ...
    "Micro-arousal"];

binLabels = { ...
    'ZT3-6', ...
    'ZT6-9'};

WTcolor = [0.25 0.25 0.25];
APPcolor = [0.75 0.20 0.20];

%% Figures

for v = 1:numel(views)

    viewName = views(v);

    if viewName == "all"
        Dview = BASE;
        figureTitle = ...
            'Baseline sleep architecture - combined cohorts';
    else
        Dview = BASE(BASE.cohort == viewName, :);
        figureTitle = sprintf( ...
            'Baseline sleep architecture - %s cohort', ...
            char(viewName));
    end

    fig = figure( ...
        'Color','w', ...
        'Position',[100 100 1100 800]);

    tl = tiledlayout( ...
        2,2, ...
        'TileSpacing','compact', ...
        'Padding','compact');

    title(tl, figureTitle);

    for s = 1:numel(states)

        ax = nexttile;
        hold(ax,'on');

        for b = 1:numel(bins)

            D = Dview( ...
                Dview.time_bin == bins(b) & ...
                Dview.state == states(s), :);

            wt = double( ...
                D.percent_time(D.genotype == "WT"));

            app = double( ...
                D.percent_time(D.genotype == "APP"));

            plot_group( ...
                ax, ...
                b - 0.13, ...
                wt, ...
                WTcolor, ...
                'o');

            plot_group( ...
                ax, ...
                b + 0.13, ...
                app, ...
                APPcolor, ...
                'o');

        end

        xlim(ax,[0.5 2.5]);

        xticks(ax,[1 2]);
        xticklabels(ax,binLabels);

        ylabel(ax,'Time in state (%)');

        title(ax,stateLabels(s));

        box(ax,'off');

        if s == 1

            hWT = plot( ...
                ax,nan,nan,'o', ...
                'MarkerFaceColor',WTcolor, ...
                'MarkerEdgeColor',WTcolor);

            hAPP = plot( ...
                ax,nan,nan,'o', ...
                'MarkerFaceColor',APPcolor, ...
                'MarkerEdgeColor',APPcolor);

            legend( ...
                ax, ...
                [hWT hAPP], ...
                {'WT','APP/PS1'}, ...
                'Location','best', ...
                'Box','off');
        end
    end

    pngFile = fullfile( ...
        outDir, ...
        sprintf( ...
            'baseline_state_percent_%s.png', ...
            char(viewName)));

    figFile = fullfile( ...
        outDir, ...
        sprintf( ...
            'baseline_state_percent_%s.fig', ...
            char(viewName)));

    exportgraphics( ...
        fig, ...
        pngFile, ...
        'Resolution',300);

    savefig(fig,figFile);

end

%% Console results

fprintf('\n========================================\n');
fprintf('WELCH APP VS WT RESULTS\n');
fprintf('========================================\n\n');

disp(WELCH(:, { ...
    'cohort_view', ...
    'time_bin', ...
    'state', ...
    'n_WT', ...
    'n_APP', ...
    'WT_mean', ...
    'APP_mean', ...
    'APP_minus_WT', ...
    'p_welch'}));

fprintf('\n========================================\n');
fprintf('COMBINED GENOTYPE x COHORT MODEL\n');
fprintf('========================================\n\n');

disp(MODEL);

fprintf('\nOutputs saved to:\n%s\n', outDir);

%% Local functions

function tf = to_logical(x)

if islogical(x)

    tf = x;

elseif isnumeric(x)

    tf = x ~= 0;

else

    x = lower(strtrim(string(x)));

    tf = ismember( ...
        x, ...
        ["1","true","yes","y"]);
end

end


function plot_group(ax, xPosition, values, color, marker)

values = values(~isnan(values));

n = numel(values);

if n == 0
    return;
end

if n == 1

    jitter = 0;

else

    jitter = linspace( ...
        -0.035, ...
        0.035, ...
        n)';
end

scatter( ...
    ax, ...
    xPosition + jitter, ...
    values, ...
    38, ...
    'Marker',marker, ...
    'MarkerEdgeColor',color, ...
    'LineWidth',1.2);

m = mean(values);
sem = std(values) / sqrt(n);

errorbar( ...
    ax, ...
    xPosition, ...
    m, ...
    sem, ...
    marker, ...
    'Color',color, ...
    'MarkerFaceColor',color, ...
    'MarkerEdgeColor',color, ...
    'MarkerSize',7, ...
    'LineWidth',1.8, ...
    'CapSize',10);

end
